DESIGNS.folding = {
  id:'folding', name:'Folding picnic bench',
  blurb:'Picnic table that folds into a backed bench. Four pivots, three rigid assemblies, hard stops and lock pins at both ends.',
  info:{ designer:'—', version:'2.1.0 (P1 rev 2 · V2)', license:'MIT' },
  areas:[
    {g:'rail', label:'Frame members', def:[38,89], hint:'Legs, bearers, pivot arms. The mechanism is validated for 38×89 only.'},
    {g:'slat', label:'Seat & table boards', def:[38,89], hint:'Tabletop / backrest, front and rear seats.'},
    {g:'stop', label:'Stops', def:[38,89], hint:'S1, T4 and T5 hard stops — cut from frame offcuts.'}
  ],
  schema:[
    {k:'L',     label:'Length', group:'Dimensions', type:'range', min:1200, max:1900, step:10, def:1520, unit:'mm'},
    {k:'fold',  label:'Fold, table → bench', group:'Mechanism', type:'range', min:0, max:100, step:1, def:0, unit:'°'},
    {k:'motion',label:'Front seat while folding', group:'Mechanism', type:'select', def:'hands',
       options:[{v:'hands',label:'Hands-off'},{v:'guided',label:'Held level'}]},
    {k:'conn',  label:'Show pivots, pins, bolts & screws', group:'Mechanism', type:'bool', def:true}
  ],
  variants:{
    P1:{ name:'P1 Rev 2', tag:'1520 long, 38×89 throughout. Stops T4/T5, lock pins, bushed pivots.',
         note:'<b>P1 Rev 2.</b> Matches <code>folding-P1/rev2/</code>: T3 removed, T4 spread stop and T5 bench stop added, '+
              'T2 and S1 lengthened, bushed M10 pivots, Ø10 indexing lock pin. Drag <i>Fold</i> to run the mechanism; '+
              '<i>Hands-off</i> lets the front seat hang under gravity the way it really will.',
         set:{ L:1520, fold:0, motion:'hands', conn:true } },
    V2:{ name:'V2 Simple', tag:'1520 long, 38×89 throughout. Two pivots per side, three flush stops, 3-board seats.',
         note:'<b>V2.</b> Matches <code>folding-V2/</code>, drawn from the video: rear seat on splayed legs, '+
              'table on a straight strut, front seat triangulated by the long arm, which is the outermost part. '+
              'All 38×89. Three stops cut from offcuts and set flush with the parts they sit on: T3 (table end), '+
              'T4 (under the table, takes the arm in bench pose) and R5 (over the back leg, takes the strut in bench pose).',
         set:{ L:1520, fold:0, motion:'hands', conn:true } }
  },
  build:function(P, ctx, variantId){
    var F = FOLDING_SETS[variantId] || FOLDING_P1, d = (P.L - F.L0)/2;
    var isV2 = F === FOLDING_V2, M = F.meta || {};
    var th = -Math.max(0, Math.min(100, P.fold));
    var st = ctx.stock('rail');
    if(st.t !== 38 || st.w !== 89)
      ctx.warnings.push('Folding P1 geometry is fixed to 38 × 89 — stock '+st.t+'×'+st.w+' is priced but not modelled');

    /* front seat orientation: held level, or the simulated hands-off path */
    var phi = 0;
    if(P.motion !== 'guided'){
      var H = F.handsoff, i = 0;
      while(i < H.length-2 && H[i+1][0] > th) i++;
      var a = H[i], b = H[i+1], f = (a[0]===b[0]) ? 0 : (th - a[0])/(b[0]-a[0]);
      phi = a[1] + f*(b[1]-a[1]);
    }
    var A = rot2(F.A0, F.B, th), dA = [A[0]-F.A0[0], A[1]-F.A0[1]];
    function tf(asm){
      if(asm === 'top')   return function(q){ return rot2(q, F.B, th); };
      if(asm === 'front') return function(q){ var r = rot2(q, F.A0, phi); return [r[0]+dA[0], r[1]+dA[1]]; };
      return function(q){ return q; };
    }
    function lift(asm){ var v = tf(asm)([0,1]), o = tf(asm)([0,0]); return [0, v[0]-o[0], v[1]-o[1]]; }

    F.parts.forEach(function(p){
      var poly = p.poly.map(tf(p.asm));
      var o = { cut:p.blank, flat:p.flat, W:p.W, note:p.note, partId:p.id, stockW:p.stockW };
      if(p.side === 'C'){
        o.cut = p.blank + 2*d; o.flat = null; o.T = 38;
        ctx.prism(p.name, p.g, p.x0 - d, p.x1 + d, poly, lift(p.asm), o);
      } else {
        ctx.prism(p.name, p.g, p.x0 + d, p.x1 + d, poly, [1.1,0,0], o);
        ctx.prism(p.name, p.g, -(p.x1 + d), -(p.x0 + d), poly, [-1.1,0,0], o);
      }
    });

    var atTable = P.fold <= 0, atBench = P.fold >= 100;
    if(P.conn){
      F.marks.forEach(function(m){
        var c = tf(m.asm)([m.y, m.z]);
        [1,-1].forEach(function(sx){
          var xf = sx*(m.x + d), poly, h, g, nm;
          if(m.k === 'pivot'){ poly = ngon(c, 15, 16); h = 3; g = 'pivot'; nm = 'Pivot '+m.label+' · bushed M10'; }
          else if(m.k === 'pin'){ poly = ngon(c, 6, 12); h = (atTable||atBench) ? 28 : 3; g = 'pin';
                                  nm = 'Lock pin Ø10'+((atTable||atBench) ? ' · engaged' : ' · pulled'); }
          else if(m.k === 'm8'){ poly = ngon(c, 8, 6, 30); h = 2; g = 'bolt'; nm = 'M8 bolt · '+m.joint; }
          else if(m.k === 'screw'){ poly = ngon(c, 4, 8); h = 1.5; g = 'screw'; nm = '5×70 screw · '+m.joint; }
          else if(m.k === 'boardscrew'){
            var n = lift(m.asm), cc = [c[0]+n[1]*1.5, c[1]+n[2]*1.5];
            ctx.prism('5×70 board screw · '+m.joint, 'screw', xf-3, xf+3, ngon(cc, 3.5, 8), [sx*1.1,0,0], { bom:false });
            return;
          } else return;
          var x0 = sx > 0 ? xf : xf - h, x1 = sx > 0 ? xf + h : xf;
          ctx.prism(nm, g, x0, x1, poly, [sx*1.3,0,0], { bom:false });
        });
      });
    }

    var V = F.validation, bayTop = 2*(631 + d), mode = atTable ? 'TABLE' : atBench ? 'BENCH' : 'FOLDING';
    var checks = isV2 ? [
      { s: V.guided===0 ? 'ok':'fail', t:'<b>Mechanism, held level.</b> 0–100° swept in 0.25° steps against every timber pair and the floor.', v: V.guided+' clashes' },
      { s: V.jams===0 ? 'ok':'fail', t:'<b>Mechanism, hands-off.</b> Front seat hangs from A under gravity and rides the floor; it comes down on both feet at each end. No jams.', v: V.jams+' jams' },
      { s: V.fasteners===0 ? 'ok':'fail', t:'<b>Fasteners in 3D.</b> Screws, M8 bolts, pivots and pin holes: spacing, ≥ 9 mm edge distance, clear of pivot B.', v: V.fasteners+' clashes' },
      { s: (V.overtravel.table_opens || V.overtravel.bench_folds) ? 'fail':'ok', t:'<b>No over-travel (pin out).</b> Searched every front-seat tilt within ±15°: the table cannot open past flat (T3) and the bench cannot fold past 100° (T4, R5).', v: (V.overtravel.table_opens || V.overtravel.bench_folds) ? 'moves' : 'locked' },
      { s:'ok', t:'<b>Endpoints locked (pin in).</b> Table: unfolding '+V.rigidity.pin_in.table['unfold 1°']+'; folding needs the whole front seat lifted. '+
              'Bench: '+V.rigidity.pin_in.bench['fold 1° more']+' both ways. The pin (or a rope, as in the video) only stops the front seat swinging while you lift.', v:'pin r '+V.pin.radius_from_A+' mm' },
      { s:'warn', t:'<b>Not load-rated.</b> Glue on the strut-to-apron lap, the arm laps and the stops is mandatory. Proof-load a prototype — see folding-V2/design-notes.md.', v:'prototype' },
      { s: mode==='FOLDING' ? 'warn':'ok', t:'<b>Pose: '+mode+'.</b> '+
          (atTable ? 'Pins in the "table" holes; F1 on T3; front seat on its two feet.' :
           atBench ? 'Pins in the "bench" holes; F1 on T4, strut on R5, front seat on its two feet.' :
           'Pins out. Table at '+(-th)+'°, front seat '+(P.motion==='guided' ? 'held level' : 'tilted '+phi.toFixed(0)+'°')+'.'), v: (-th)+'°' }
    ] : [
      { s: V.guided===0 ? 'ok':'fail', t:'<b>Mechanism, held level.</b> 0–100° swept in 0.25° steps against every timber pair.', v: V.guided+' clashes' },
      { s: V.jams===0 ? 'ok':'fail', t:'<b>Mechanism, hands-off.</b> Front seat hangs from A under gravity, rides the floor and the rear frame, confined between T4 (0°) and T5 (100°). No jams.', v: V.jams+' jams' },
      { s: V.fasteners===0 ? 'ok':'fail', t:'<b>Fasteners in 3D.</b> Screws, M8 bolts, pivot counterbores and pin holes checked against each other.', v: V.fasteners+' clashes' },
      { s:'ok', t:'<b>Endpoints locked.</b> Table: '+V.rigidity.table['+1°']+' / pin stops folding. Bench: '+V.rigidity.bench['+1°']+' and '+V.rigidity.bench['−1°']+' with the pin in.', v:'pin r '+V.pin.radius_from_A+' mm' },
      { s:'warn', t:'<b>Not load-rated.</b> T4 reacts ≈4 kN per side in the worst case (two adults on the front seat, leaning on the table, slippery floor). Glue on T4/T1 is mandatory. Proof-load a prototype before release — see design-review.md.', v:'prototype' },
      { s: mode==='FOLDING' ? 'warn':'ok', t:'<b>Pose: '+mode+'.</b> '+
          (atTable ? 'Pins in the "table" holes; F1 bears on T4.' : atBench ? 'Pins in the "bench" holes; F1 bears on T5, T2 on S1, S2 on R3.' :
           'Pins out. Table at '+(-th)+'°, front seat '+(P.motion==='guided' ? 'held level' : 'tilted '+phi.toFixed(0)+'°')+
           ((P.motion!=='guided' && th <= -53.5) ? ' — S2 sliding over the R3 corner (R6 round-over).' : '.')), v: (-th)+'°' }
    ];
    if(d !== 0) checks.push({ s:'ok', t:'Length changed by '+(2*d)+' mm: boards and frame spacing follow; the side profile, pivots and stops are unchanged.', v:P.L+' mm' });

    return {
      parts: ctx.parts,
      spans: isV2 ? [{ label:'Tabletop / backrest boards', span:bayTop, b:M.boardW, h:38, tributary:M.boardW+6, load:2 },
                     { label:'Seat boards', span:2*(552 + d), b:M.seatW, h:38, tributary:M.seatW+6, load:2 }]
                  : [{ label:'Tabletop / backrest boards', span:bayTop, b:89, h:38, tributary:95, load:2 }],
      headline: isV2 ? P.L+' × '+M.tableDepth+' mm tabletop · '+M.tableHeight+' high · seats '+M.seatHeight+' · bench seat '+M.seatDepth+' deep · backrest '+M.backTop+' high'
                     : P.L+' × 469 mm tabletop · 755 high · seats 450 · combined bench seat 374 deep',
      headline2: isV2 ? 'V2 · '+mode+(mode==='FOLDING' ? ' '+(-th)+'° · pins out' : ' · pins in')+' · 3 sub-assemblies · 2 pivots per side · not load-rated'
                      : 'Rev 2 · '+mode+(mode==='FOLDING' ? ' '+(-th)+'° · pins out' : ' · pins in')+
                 ' · T3 removed · T4/T5 stops · bushed pivots · not load-rated',
      hardware: F.hardware, joints: F.joints, interfaces: F.interfaces, checks: checks,
      fabrication: F.fabrication || [
        { part:'Pivots A, B', detail:'Bore Ø18, press 14/18 bushings flush with the moving faces, Ø14 stainless sleeve 54.5 long, M10×70 + nyloc tightened fully, 3 mm UHMW thrust washer. Counterbore Ø30: 10 deep head side, 15 deep nut side.' },
        { part:'Lock pin', detail:'Match-drill Ø10.5 through F1 into T1 in each locked pose (table, then bench).' },
        { part:'Stops', detail:'T4 flush with the table end, bearing on F1 upper flank; T5 under the tabletop, bearing on F1 rear flank in bench pose; S1 lapped full height on R4. Glue + screws; T4 also 1 × M8.' },
        { part:'Sliding corner', detail:'R6 round-over on R3 front-top corner; ease S2 lower arrises 3 mm.' },
        { part:'Drawings', detail:'folding-P1/rev2/: connections-*.svg, pivot-sections.svg, drilling.svg, joint-schedule.csv, design-review.md.' }
      ]
    };
  }
};
