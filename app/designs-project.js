/* ---- folding picnic bench, Rev 2 --------------------------------------- */
function rot2(p, c, deg){
  var a = deg*Math.PI/180, x = p[0]-c[0], y = p[1]-c[1];
  return [c[0] + x*Math.cos(a) - y*Math.sin(a), c[1] + x*Math.sin(a) + y*Math.cos(a)];
}
function ngon(c, r, n, rotDeg){
  var out = [], a0 = (rotDeg||0)*Math.PI/180;
  for(var i=0;i<n;i++){ var a = a0 + i*2*Math.PI/n; out.push([c[0]+r*Math.cos(a), c[1]+r*Math.sin(a)]); }
  return out;
}

