/* Frame bench shared by simple and modern. Rules recovered from the G1/M1/M2
   exports:
     - posts on the line ±(L/2 − t/2); long seat rails on the post line in Y
     - side rails and bearers span between the long rails' inner faces
     - bearers split the long rail into equal bays until the seat-board span
       is ≤ 16 × board thickness (rule of thumb)
     - seat boards spread from 4 mm in front of the rear uprights to the front
     - back boards on the back of the uprights, spread from Hseat+40 to Hback
     - modern: arm rail on the front legs at Harm, lower side tie at 120 */
function frameBench(P, ctx, arms){
  var post = ctx.built('post', 1), rail = ctx.built('rail', 1);
  var slat = ctx.built('slat', 1), back = ctx.built('back', 1);
  var arm  = arms ? ctx.built('arm', 1) : null;
  var X0 = P.L/2 - post.a/2, yF = P.D/2 - post.b/2, yR = -yF;
  var Hleg = arms ? P.Harm - arm.b : P.Hseat - slat.a;
  var railZ = P.Hseat - slat.a - rail.b/2;
  var sideLen = ctx.span('Side seat rail', 2*(yF - rail.a/2));
  var Lr = ctx.span('Long seat rail', P.L - 2*post.a);

  [-1,1].forEach(function(sx){
    ctx.box('Front leg','post',1,[post.a,post.b,Hleg],[sx*X0,yF,Hleg/2],[sx,1,-0.4]);
    ctx.box('Rear upright','post',1,[post.a,post.b,P.Hback],[sx*X0,yR,P.Hback/2],[sx,-1,0]);
    ctx.box('Side seat rail','rail',1,[rail.a,sideLen,rail.b],
            [sx*(P.L/2-post.a-rail.a/2),0,railZ],[sx,0,-0.3]);
    if(arms){
      var a0 = yR + post.b/2, a1 = P.D/2;
      ctx.box('Arm rail','arm',1,[arm.a,a1-a0,arm.b],[sx*X0,(a0+a1)/2,P.Harm-arm.b/2],[sx,0,1]);
      ctx.box('Lower side tie','arm',1,[arm.a,2*(yF-post.b/2),arm.b],[sx*X0,0,120],[sx,0,-1]);
    }
  });
  ctx.box('Long seat rail','rail',1,[Lr,rail.a,rail.b],[0,yR,railZ],[0,-1,-0.5]);
  ctx.box('Long seat rail','rail',1,[Lr,rail.a,rail.b],[0,yF,railZ],[0,1,-0.5]);

  var maxSpan = 16*slat.a, nb = 0;
  while(Lr/(nb+1) - rail.a > maxSpan && nb < 12) nb++;
  var bay = Lr/(nb+1), stations = [rail.a/2];
  for(var k=1;k<=nb;k++){
    var x = -Lr/2 + k*bay;
    ctx.box('Intermediate bearer','rail',1,[rail.a,sideLen,rail.b],[x,0,railZ],[0,0,-1]);
    stations.push(Lr/2 + x);
  }
  stations.push(Lr - rail.a/2);

  var s0 = yR + post.b/2 + 4;
  var seat = ctx.spread(ctx.span('Seat', P.D/2 - s0), slat.b, P.seatGap, s0);
  seat.centres.forEach(function(y){
    ctx.box('Seat board','slat',1,[Lr,slat.b,slat.a],[0,y,P.Hseat-slat.a/2],[0,0,1]);
  });
  var zb0 = P.Hseat + 40;
  var bk = ctx.spread(ctx.span('Back', P.Hback - zb0), back.b, 45, zb0);
  var yb = yR - post.b/2 - back.a/2;
  bk.centres.forEach(function(z){
    ctx.box('Back board','back',1,[P.L,back.a,back.b],[0,yb,z],[0,-1,0.5]);
  });

  var nSup = nb + 2, brackets = arms ? 12 : 8;
  var frame = 8 + 8 + 4*nb + (arms ? 16 : 0);
  var backScrew = Math.round(back.a + 38);
  var hw = [
    { id:'HW-S1', qty:frame, spec:'Exterior structural wood screw 6 × 110 mm, rated for frame joints',
      note:'Two per rail end; four per intermediate bearer'+(arms?'; arms and lower ties two per end':'')+'. Verify angle and embedment at each butt joint.' },
    { id:'HW-S2', qty:2*seat.n*nSup, spec:'Exterior seat screw 5 × 70 mm',
      note:'Two per seat board at each end rail and each bearer; stagger to avoid splitting.' },
    { id:'HW-S3', qty:2*bk.n*2, spec:'Exterior back screw 5 × '+backScrew+' mm',
      note:'Two per back board at each rear upright, on the upright centre line.' },
    { id:'HW-S4', qty:brackets, spec:'Galvanized / stainless corner bracket, 50 × 50 mm minimum',
      note:'Seat perimeter'+(arms?' and lower ties':'')+' against racking.' },
    { id:'HW-S5', qty:brackets*4, spec:'Bracket-manufacturer approved exterior connector screws',
      note:'Four per bracket allowance.' },
    { id:'HW-S6', qty:4, spec:'Non-absorbent exterior foot pads for '+post.a+' × '+post.b+' posts',
      note:'Pad thickness adds to the overall height.' }
  ];
  var fab = [
    { part:'All timber', detail:'All ends square; no laps, rebates or mitres. Finished stock sizes. Break exposed edges 2–3 mm.' },
    { part:'Frame joints', detail:'Rails butt against posts; bearer ends butt against long rails. Brackets are required against racking.' },
    { part:'Seat board drilling', detail:'Two holes per support, 20 mm from each long edge. Support stations from the inner seat left end: '+
        stations.map(function(s){ return Math.round(s*10)/10; }).join(', ')+' mm. Do not drill at the board end.' },
    { part:'Back board drilling', detail:'Upright centre lines at '+(post.a/2)+' and '+(P.L-post.a/2)+' mm from the board left end; two screws per upright, 20 mm from each long edge.' },
    { part:'Design scope', detail:'Connection capacity, species/grade and user loading require workshop verification; no tested load rating is claimed.' }
  ];
  return {
    parts: ctx.parts,
    spans: [{ label:'Seat boards', span:bay - rail.a, b:slat.b, h:slat.a, tributary:slat.b+seat.gap, load:2 }],
    headline: P.L+' × '+P.D+' mm · seat '+P.Hseat+' · back '+P.Hback+' mm',
    headline2: seat.n+' seat boards · '+bk.n+' back boards · '+nb+' intermediate bearer'+(nb===1?'':'s')+' · square cuts',
    hardware: hw, fabrication: fab
  };
}

